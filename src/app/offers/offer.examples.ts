import { OfferCatalog, OfferDateRange, OfferField } from './offer.types';

const today = new Date();
today.setHours(0, 0, 0, 0);

function dateOffset(days: number): string {
  const date = new Date(today);
  date.setDate(date.getDate() + days);
  return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`;
}

function period(startOffset: number, endOffset: number): OfferField<OfferDateRange> {
  return {
    status: 'known',
    value: { startDate: dateOffset(startOffset), endDate: dateOffset(endOffset) },
  };
}

